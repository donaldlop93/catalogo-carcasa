-- ============================================================================
-- BASE DE DATOS SUPABASE - CATÁLOGO DIGITAL CARCASA JINOTEGA
-- ============================================================================
-- Este script crea las tablas, políticas de seguridad (RLS), almacenamiento 
-- (Storage) y datos iniciales para el catálogo digital de CARCASA Jinotega.
-- ============================================================================

-- 1. TABLA DE CATEGORÍAS
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    imagen TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. TABLA DE PRODUCTOS (EQUIPOS)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    codigo TEXT,
    nombre TEXT NOT NULL,
    marca TEXT,
    modelo TEXT,
    categoria TEXT NOT NULL,
    descripcion TEXT,
    specs JSONB DEFAULT '[]'::jsonb,
    moneda TEXT DEFAULT '$' CHECK (moneda IN ('$', 'C$')),
    precio TEXT,
    disponibilidad TEXT DEFAULT 'Disponible',
    destacado BOOLEAN DEFAULT false,
    activo BOOLEAN DEFAULT true,
    imagenes JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Índices de búsqueda rápida
CREATE INDEX IF NOT EXISTS idx_productos_slug ON public.productos(slug);
CREATE INDEX IF NOT EXISTS idx_productos_categoria ON public.productos(categoria);
CREATE INDEX IF NOT EXISTS idx_productos_destacado ON public.productos(destacado);
CREATE INDEX IF NOT EXISTS idx_productos_activo ON public.productos(activo);

-- 3. TABLA DE CONFIGURACIÓN INSTITUCIONAL
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.configuracion (
    id TEXT PRIMARY KEY DEFAULT 'main',
    whatsapp TEXT NOT NULL DEFAULT '50557079297',
    phone_display TEXT NOT NULL DEFAULT '+505 5707-9297',
    email TEXT DEFAULT 'ventas@carcasajinotega.com',
    schedule TEXT DEFAULT 'Lunes a Sábado: 8:00 AM - 5:30 PM',
    address TEXT DEFAULT 'Frente a Gasolinera Puma Apanás, Jinotega, Nicaragua.',
    facebook TEXT DEFAULT 'https://facebook.com',
    hero_title TEXT DEFAULT 'Maquinaria, equipos y soluciones para impulsar tu trabajo.',
    hero_subtitle TEXT DEFAULT 'Encuentra maquinaria agrícola, equipos industriales, herramientas y repuestos con asesoramiento técnico especializado.',
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 4. POLÍTICAS DE SEGURIDAD (ROW LEVEL SECURITY - RLS)
-- ----------------------------------------------------------------------------
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.configuracion ENABLE ROW LEVEL SECURITY;

-- Políticas para Categorías:
-- Lectura pública para cualquier usuario (anónimo o autenticado)
CREATE POLICY "Permitir lectura pública de categorias" 
ON public.categorias FOR SELECT 
USING (true);

-- Escritura solo para administradores autenticados
CREATE POLICY "Permitir escritura solo a usuarios autenticados en categorias" 
ON public.categorias FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

-- Políticas para Productos:
-- El público puede ver los productos activos. Los autenticados ven todos.
CREATE POLICY "Permitir lectura de productos activos al publico" 
ON public.productos FOR SELECT 
USING (activo = true OR auth.role() = 'authenticated');

-- Crear, actualizar y eliminar solo para usuarios autenticados
CREATE POLICY "Permitir escritura de productos solo a usuarios autenticados" 
ON public.productos FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

-- Políticas para Configuración:
-- Lectura pública de los datos de contacto y portada
CREATE POLICY "Permitir lectura publica de configuracion" 
ON public.configuracion FOR SELECT 
USING (true);

-- Modificación solo para administradores autenticados
CREATE POLICY "Permitir edicion de configuracion solo a autenticados" 
ON public.configuracion FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

-- 5. BUCKET DE ALMACENAMIENTO PARA FOTOGRAFÍAS (STORAGE)
-- ----------------------------------------------------------------------------
-- Crear el bucket 'equipos' como público para servir imágenes rápidamente
INSERT INTO storage.buckets (id, name, public)
VALUES ('equipos', 'equipos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas de Storage para el bucket 'equipos':
-- Lectura pública de imágenes
CREATE POLICY "Acceso publico de lectura a imagenes de equipos" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'equipos');

-- Subida y modificación de imágenes solo por usuarios autenticados
CREATE POLICY "Subida de imagenes por usuarios autenticados" 
ON storage.objects FOR INSERT 
TO authenticated 
WITH CHECK (bucket_id = 'equipos');

CREATE POLICY "Modificacion de imagenes por usuarios autenticados" 
ON storage.objects FOR UPDATE 
TO authenticated 
USING (bucket_id = 'equipos');

CREATE POLICY "Eliminacion de imagenes por usuarios autenticados" 
ON storage.objects FOR DELETE 
TO authenticated 
USING (bucket_id = 'equipos');

